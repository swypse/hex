/** Eight compass points plus the middle of the map, as seen on screen
 *  (north is up). */
export enum CompassDirection {
  CENTER = 'center',
  NORTH = 'north',
  NORTHEAST = 'northeast',
  EAST = 'east',
  SOUTHEAST = 'southeast',
  SOUTH = 'south',
  SOUTHWEST = 'southwest',
  WEST = 'west',
  NORTHWEST = 'northwest',
}
